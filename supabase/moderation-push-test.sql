begin;
do $$
declare seller uuid:=gen_random_uuid(); buyer uuid:=gen_random_uuid(); moderator uuid:=gen_random_uuid(); listing uuid:=gen_random_uuid();
  msg uuid:=gen_random_uuid(); msg2 uuid:=gen_random_uuid(); r1 uuid:=gen_random_uuid(); r2 uuid:=gen_random_uuid();
  comment uuid:=gen_random_uuid(); r3 uuid:=gen_random_uuid(); ids uuid[]; all_ids uuid[]:='{}'; receipt uuid; amount integer; denied boolean;
begin
  insert into auth.users(id) values(seller),(buyer),(moderator);
  insert into public.auto_moderators(user_id) values(moderator);
  perform set_config('request.jwt.claim.sub',seller::text,true);
  insert into public.auto_listings(id,owner_id,plate_left,plate_digits,plate_right,region,price_rub,status) values(listing,seller,'А','129','ВС','77',100000,'active');
  insert into public.listing_messages(id,listing_id,sender_id,recipient_id,body) values(msg,listing,seller,buyer,'Test message'),(msg2,listing,seller,buyer,'Test second message');
  insert into public.listing_public_comments(id,listing_id,author_id,author_name,body) values(comment,listing::text,seller,'Test seller','Test comment');
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  insert into public.listing_message_reports(id,message_id,reason) values(r1,msg,'Test complaint'),(r2,msg2,'Test false complaint');
  insert into public.listing_public_comment_reports(id,comment_id,reason) values(r3,comment,'Test comment complaint');
  execute 'set local role authenticated';
  denied:=false;
  begin perform public.moderate_report_with_push(r1,'message','reported','warning',null,'Test warning'); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'FAIL: ordinary user creates moderation pushes'; end if;
  perform set_config('request.jwt.claim.sub',moderator::text,true);
  select p.push_job_ids into ids from public.moderate_report_with_push(r1,'message','reported','warning',null,'Пожалуйста, соблюдайте правила.') p;
  if array_length(ids,1)<>2 then raise exception 'FAIL: warning must notify subject and reporter'; end if;
  all_ids:=all_ids||ids;
  select p.push_job_ids into ids from public.moderate_report_with_push(r3,'comment','reported','ban',60,'Повторное нарушение.') p;
  if array_length(ids,1)<>2 then raise exception 'FAIL: ban must notify both participants'; end if;
  all_ids:=all_ids||ids;
  select p.push_job_ids into ids from public.moderate_report_with_push(r2,'message','reporter','warning',null,'Жалоба не соответствует переписке.') p;
  if array_length(ids,1)<>1 then raise exception 'FAIL: false report sends only reporter punishment'; end if;
  all_ids:=all_ids||ids;
  denied:=false;
  begin perform public.claim_moderation_push_jobs(all_ids,moderator); exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'FAIL: client can claim jobs directly'; end if;
  execute 'reset role';
  if not exists(select 1 from public.moderation_push_jobs j where j.report_id=r1 and j.audience='subject' and j.owner_id=seller and j.body='Пожалуйста, соблюдайте правила.') then raise exception 'FAIL: warning target payload'; end if;
  if not exists(select 1 from public.moderation_push_jobs j where j.report_id=r3 and j.audience='subject' and j.body like '%МСК.%Повторное нарушение.%') then raise exception 'FAIL: ban duration and description missing'; end if;
  if exists(select 1 from public.moderation_push_jobs j where j.audience='reporter' and j.body like '%Повторное нарушение%') then raise exception 'FAIL: private moderation description disclosed in receipt'; end if;
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  execute 'set local role authenticated';
  select count(*) into amount from public.moderation_push_jobs;
  if amount<>2 then raise exception 'FAIL: reporter cannot read own receipts or sees subject push data'; end if;
  select j.id into receipt from public.moderation_push_jobs j where j.report_id=r1;
  denied:=false;
  begin update public.moderation_push_jobs set body='Forged push' where id=receipt; exception when insufficient_privilege then denied:=true; end;
  if not denied then raise exception 'FAIL: receipt user can modify outgoing push'; end if;
  update public.moderation_push_jobs set read_at=now() where id=receipt;
  execute 'reset role';
  execute 'set local role service_role';
  select count(*) into amount from public.claim_moderation_push_jobs(all_ids,moderator);
  if amount<>5 then raise exception 'FAIL: service failed to claim notifications'; end if;
  select count(*) into amount from public.claim_moderation_push_jobs(all_ids,moderator);
  if amount<>0 then raise exception 'FAIL: duplicate claim allowed'; end if;
  execute 'reset role';
end;
$$;
rollback;
